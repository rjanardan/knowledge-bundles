#!/usr/bin/env python3
"""build-index - generate the bundle root index and per-directory indexes.

Run from anywhere:  python3 _tools/build-index.py

index.md is reserved by the OKF specification and carries no frontmatter except
okf_version at the root, so these files are generated rather than authored.
Hand edits are lost on the next run.
"""
import datetime
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("build-index: PyYAML is required (python3 -m pip install pyyaml)")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)

TITLE = "The future of software development"
BLURB = ("Roles, lifecycle phases and the tooling that changed them, kept in two epistemics: "
         "measured findings under `evidence/`, attributed predictions under `forecasts/`.")

DIRS = [
    ("companies", "Companies",
     "Organisations that build, sell or standardise software-delivery tooling."),
    ("roles", "Roles",
     "Job functions in software delivery, each with a past, present and future axis."),
    ("sdlc", "SDLC phases",
     "Lifecycle phases in order, and what each one has lost to automation."),
    ("practices", "Practices",
     "Methodologies that span several phases."),
    ("evidence", "Evidence",
     "Measured findings, each with a method, a sample and an interval."),
    ("forecasts", "Forecasts",
     "Attributed predictions, each with a written falsifier."),
    ("technologies", "Technologies",
     "Tools, protocols and standards."),
    ("people", "People",
     "Practitioners, researchers and executives."),
    ("timeline", "Timeline",
     "Derived chronological views over the concepts in this bundle."),
]


def read(path):
    text = open(path, encoding="utf-8").read()
    m = FM_RE.match(text)
    fm = {}
    if m:
        try:
            fm = yaml.safe_load(m.group(1)) or {}
        except Exception:  # noqa: BLE001
            fm = {}
    return fm


def concepts(d):
    full = os.path.join(ROOT, d)
    if not os.path.isdir(full):
        return []
    out = []
    for name in sorted(os.listdir(full)):
        if name.endswith(".md") and name != "index.md":
            fm = read(os.path.join(full, name))
            out.append((name, fm.get("title", name[:-3]), fm.get("type", "?"),
                        (fm.get("description") or "").strip()))
    return out


def main():
    generated, populated, counts = [], [], {}
    for d, label, blurb in DIRS:
        rows = concepts(d)
        if not rows:
            continue
        populated.append((d, label, len(rows)))
        counts[d] = len(rows)
        lines = [f"# {label}", "",
                 f"{len(rows)} concepts. {blurb} Generated by `_tools/build-index.py`; "
                 "hand edits are lost.", "",
                 "| Concept | Type | Summary |", "| --- | --- | --- |"]
        for name, title, typ, desc in rows:
            lines.append(f"| [{title}]({name}) | {typ} | {desc} |")
        lines.append("")
        open(os.path.join(ROOT, d, "index.md"), "w").write("\n".join(lines))
        generated.append(f"{d}/index.md")

    empty = [(d, label, blurb) for d, label, blurb in DIRS if d not in counts]

    meta = sorted(f for f in os.listdir(ROOT)
                  if f.endswith(".md") and f not in {"index.md", "log.md"})

    n_edges = 0
    for d in counts:
        for name in os.listdir(os.path.join(ROOT, d)):
            if name.endswith(".md") and name != "index.md":
                n_edges += len(read(os.path.join(ROOT, d, name)).get("relations") or [])

    out = ['---', 'okf_version: "0.2"', '---', '',
           f"# {TITLE}", '',
           f"A knowledge bundle in Google's Open Knowledge Format v0.2. It is a graph first: "
           f"{sum(counts.values()) + len(meta)} concepts carrying {n_edges} typed edges, with "
           f"`_tools/okf-check.py` for conformance and `_tools/build-index.py` for these listings.",
           '', BLURB, '',
           "Entries are listed here for browsing; the machine-readable layer is the `relations` "
           "frontmatter block in each concept. Conventions are frozen in "
           "[conventions.md](conventions.md).", '']
    if meta:
        out += ["# Bundle-level concepts", '',
                "Concepts that live at the bundle root rather than inside a directory:", '']
        out += [f"* [{m[:-3]}]({m})" for m in meta]
        out += ['']
    for d, label, n in populated:
        out += [f"# {label}", '']
        for name, title, typ, desc in concepts(d):
            out.append(f"* [{title}]({d}/{name}) - {desc}")
        out.append('')
    if empty:
        out += ["# Directories declared but not yet populated", '',
                "Named before they exist so that a link from a populated concept resolves to a "
                "declared target. Under OKF §6.1, a link to a not-yet-written concept is not an "
                "error.", '']
        for d, label, blurb in empty:
            out.append(f"* `{d}/` - {label} - {blurb}")
        out.append('')
    out += ["# Non-concept directories", '',
            "* `images/` - media cited by concepts. Every asset carries a licence, a credit, a "
            "hash and a footnote definition line in the concept that uses it, so an asset is "
            "traceable by the same rule as a claim.",
            "* `references/captures/` - raw retrieval dumps, stored as `.txt` so the conformance "
            "checker does not read them as concepts. Each carries its retrieval date, a SHA-256 "
            "prefix and the HTTP status at fetch time.",
            "* `_tools/` - the conformance linter and this index generator.", '',
            "# How to query the graph", '',
            "These are traversals over the `relations` blocks rather than searches. They map onto "
            "the four uses this bundle was built for, which are also its acceptance test:", '',
            "* **For a paper - what is actually measured.** Read `evidence/` alone. Every concept "
            "there carries a `method`, an `n` and an `effect_ci`, and nothing there is an "
            "estimate about the future.",
            "* **For a book - how a phase changed, in order.** Walk `sdlc/` by its `order` key, "
            "then follow `changed-by` to the technologies that moved it and `practised-by` on "
            "`practices/` for the methodology layer.",
            "* **For a post - one dated, sourced shift.** Any `## Snapshot` in `roles/` names the "
            "change and its date; the supporting measurement is one hop away under `evidence/`.",
            "* **For an interview - what a company claims, and who disagrees.** Follow `claims` "
            "from `forecasts/` to its target and `contradicts` between studies. Counting "
            "`contradicts` edges is a direct read of where the field has not settled.", '',
            "Two further traversals are worth naming because they are the ones a graph buys over "
            "a folder of notes:", '',
            "* **Ownership lineage.** `owns` and `subsidiary-of` trace a tool from an independent "
            "vendor to its present owner, which is how a 2002 agile tracker becomes a 2026 "
            "value-stream product.",
            "* **Source hygiene.** `sources[].author` uses an actor namespace, so a reader can "
            "count how many of a concept's sources are first-party. A concept resting only on "
            "`org:` sources is a vendor's account of itself.", '',
            f"Generated by `_tools/build-index.py` on {datetime.date.today().isoformat()}."]
    open(os.path.join(ROOT, "index.md"), "w").write("\n".join(out) + "\n")
    print("wrote:", ", ".join(generated + ["index.md"]))
    print("concepts per directory:", counts)
    print("declared but empty:", [d for d, _, _ in empty])
    return 0


if __name__ == "__main__":
    sys.exit(main())
